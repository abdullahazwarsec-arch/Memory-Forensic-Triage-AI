from pathlib import Path

from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

BASE_DIR = Path(__file__).resolve().parents[2]
OUTPUTS_DIR = BASE_DIR / "outputs"


def create_forensic_pdf(filename="forensic_triage_report.pdf", risk_level="HIGH RISK", confidence=98.5, indicators=None):
    if indicators is None:
        indicators = [
            "Unusual memory access (malfind.ninjections detected)",
            "Hidden execution (psxview.not_in_eprocess unlinked)",
            "Abnormal service manipulation (svcscan.nservices anomalous)"
        ]

    output_path = OUTPUTS_DIR / filename
    doc = SimpleDocTemplate(str(output_path), pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
    story = []
    styles = getSampleStyleSheet()

    # Custom Styles
    title_style = ParagraphStyle(
        'TitleStyle',
        parent=styles['Heading1'],
        fontSize=18,
        textColor=colors.HexColor("#1A2B4C"),
        spaceAfter=6
    )
    
    subtitle_style = ParagraphStyle(
        'SubTitleStyle',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor("#555555"),
        spaceAfter=15
    )

    heading_style = ParagraphStyle(
        'HeadingStyle',
        parent=styles['Heading2'],
        fontSize=12,
        textColor=colors.HexColor("#1A2B4C"),
        spaceBefore=10,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        'BodyStyle',
        parent=styles['Normal'],
        fontSize=10,
        textColor=colors.HexColor("#333333"),
        spaceAfter=6
    )

    # Document Header
    story.append(Paragraph("EXPLAINABLE AI MEMORY FORENSIC INCIDENT REPORT", title_style))
    story.append(Paragraph("Generated by RAM-Triage Engine | Autonomous Memory Forensics & XAI Framework", subtitle_style))
    story.append(Spacer(1, 10))

    # Triage Summary Table
    summary_data = [
        ['Metric / Parameter', 'Investigation Details'],
        ['Risk Classification', risk_level],
        ['Malware Confidence', f"{confidence:.2f}%"],
        ['Analysis Engine', 'Random Forest + SHAP / LIME Dual Validation'],
        ['Status', 'Requires Immediate Incident Response Action']
    ]

    summary_table = Table(summary_data, colWidths=[150, 390])
    summary_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (1,0), colors.HexColor("#1A2B4C")),
        ('TEXTCOLOR', (0,0), (1,0), colors.white),
        ('ALIGN', (0,0), (-1,-1), 'LEFT'),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('FONTSIZE', (0,0), (-1,-1), 10),
        ('BOTTOMPADDING', (0,0), (-1,-1), 6),
        ('TOPPADDING', (0,0), (-1,-1), 6),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CCCCCC")),
        ('BACKGROUND', (0,1), (-1,-1), colors.HexColor("#F9F9F9")),
    ]))
    
    story.append(summary_table)
    story.append(Spacer(1, 15))

    # Forensic Indicators Section
    story.append(Paragraph("Top Explainable AI (SHAP/LIME) Indicators Identified", heading_style))
    for ind in indicators:
        story.append(Paragraph(f"• {ind}", body_style))

    story.append(Spacer(1, 15))

    # Recommended Actions
    story.append(Paragraph("Recommended Incident Response Playbook", heading_style))
    story.append(Paragraph("1. <b>Endpoint Isolation:</b> Isolate the host machine from the internal network immediately to prevent lateral movement.", body_style))
    story.append(Paragraph("2. <b>Artifact Extraction:</b> Carve out injected process memory spaces using Volatility malfind plugins.", body_style))
    story.append(Paragraph("3. <b>Threat Corroboration:</b> Cross-reference active indicators against SIEM logs and threat intelligence feeds.", body_style))

    doc.build(story)
    print(f"[+] Successfully generated PDF report: {output_path}")

if __name__ == "__main__":
    create_forensic_pdf()